import { BuilderFormData } from '../types';

export function generateContractText(data: BuilderFormData): string {
  const currentDate = new Date().toLocaleDateString('ru-RU', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });

  if (data.type === 'nda') {
    return `СОГЛАШЕНИЕ О НЕРАЗГЛАШЕНИИ КОНФИДЕНЦИАЛЬНОЙ ИНФОРМАЦИИ (NDA)

г. Москва                                                      «${currentDate}»

${data.clientName || '«Раскрывающая сторона»'}, именуемое в дальнейшем «Раскрывающая сторона», с одной стороны, и
${data.contractorName || '«Получающая сторона»'}, именуемое в дальнейшем «Получающая сторона», с другой стороны, 
совместно именуемые «Стороны», заключили настоящее Соглашение о нижеследующем:

1. ПРЕДМЕТ СОГЛАШЕНИЯ
1.1. Предметом настоящего Соглашения является охрана конфиденциальной информации, передаваемой Сторонами друг другу в связи с обсуждением и реализацией проекта: ${data.subject || 'стратегическое сотрудничество и взаимные консультации'}.
1.2. Под Конфиденциальной информацией понимаются любые научно-технические, технологические, производственные, финансово-экономические или иные сведения, переданные в письменной, электронной или иной форме.

2. ОБЯЗАТЕЛЬСТВА СТОРОН
2.1. Получающая сторона обязуется соблюдать в отношении Конфиденциальной информации такую же степень заботливости и осмотрительности, какую она применяет в отношении собственной конфиденциальной информации.
2.2. Информация не подлежит передаче третьим лицам без предварительного письменного согласия Раскрывающей стороны.
2.3. Срок охраны конфиденциальности составляет ${data.confidentialityPeriodYears || 3} (три) года с момента передачи сведений.

3. ОТВЕТСТВЕННОСТЬ СТОРОН
3.1. В случае документально подтвержденного нарушения обязательств по настоящему Соглашению виновная Сторона выплачивает штраф в размере ${data.amount ? data.amount + ' ₽' : '1 000 000 (один миллион) рублей'} за каждый факт неправомерного раскрытия.

4. ПОРЯДОК РАЗРЕШЕНИЯ СПОРОВ
4.1. Все споры подлежат разрешению с соблюдением обязательного претензионного порядка (15 рабочих дней).
4.2. При недостижении согласия спор передается на рассмотрение в ${data.jurisdiction || 'Арбитражный суд города Москвы'}.`;
  }

  if (data.type === 'lease') {
    return `ДОГОВОР АРЕНДЫ НЕЖИЛОГО ПОМЕЩЕНИЯ № АР-${Math.floor(100 + Math.random() * 900)}

г. Москва                                                      «${currentDate}»

${data.clientName || '«Арендодатель»'}, именуемый в дальнейшем «Арендодатель», с одной стороны, и
${data.contractorName || '«Арендатор»'}, именуемый в дальнейшем «Арендатор», с другой стороны, 
заключили настоящий Договор о нижеследующем:

1. ПРЕДМЕТ ДОГОВОРА
1.1. Арендодатель обязуется передать во временное владение и пользование, а Арендатор принять нежилое помещение для целей: ${data.subject || 'размещение офиса компании'}.
1.2. Срок аренды составляет ${data.termMonths || 11} месяцев с даты подписания Акта приема-передачи.

2. АРЕНДНАЯ ПЛАТА И РАСЧЕТЫ
2.1. Арендная плата устанавливается в размере ${data.amount || '450 000'} рублей в месяц, включая НДС.
2.2. Оплата производится ежемесячно не позднее 5-го числа расчетного месяца на расчетный счет Арендодателя.
2.3. Обеспечительный платеж в размере одномесячной платы вносится в течение 5 банковских дней с момента подписания.

3. ОТВЕТСТВЕННОСТЬ И РАЗРЕШЕНИЕ СПОРОВ
3.1. За просрочку внесения арендных платежей Арендодатель вправе начислить пени в размере ${data.penaltyRate || 0.1}% за каждый день просрочки, но не более 10% от суммы задолженности.
3.2. Споры, не урегулированные переговорами, передаются в ${data.jurisdiction || 'Арбитражный суд города Москвы'}.`;
  }

  // Default: Services Contract
  return `${data.title || 'ДОГОВОР ВОЗМЕЗДНОГО ОКАЗАНИЯ УСЛУГ'}

г. Москва                                                      «${currentDate}»

${data.clientName || '«Заказчик»'}, именуемое в дальнейшем «Заказчик», в лице уполномоченного представителя, с одной стороны, и
${data.contractorName || '«Исполнитель»'}, именуемое в дальнейшем «Исполнитель», с другой стороны,
совместно именуемые «Стороны», заключили настоящий Договор о нижеследующем:

1. ПРЕДМЕТ ДОГОВОРА
1.1. Исполнитель обязуется оказать Заказчику услуги: «${data.subject || 'Оказание комплекса консультационных и технических услуг'}», а Заказчик обязуется принять и оплатить оказанные услуги в порядке и на условиях настоящего Договора.
1.2. Срок оказания услуг: в течение ${data.termMonths || 2} месяцев с момента перечисления авансового платежа.

2. СТОИМОСТЬ УСЛУГ И ПОРЯДОК ОПЛАТЫ
2.1. Общая стоимость услуг составляет ${data.amount || '1 200 000'} рублей (НДС не облагается в связи с применением УСН).
2.2. Заказчик выплачивает аванс в размере ${data.prepaymentPercent || 30}% в течение 5 (пяти) банковских дней с даты подписания Договора.
2.3. Окончательный расчет производится в течение 5 (пяти) банковских дней с даты подписания двустороннего Акта сдачи-приемки.

3. ИНТЕЛЛЕКТУАЛЬНЫЕ ПРАВА
3.1. ${data.ipTransfer 
  ? 'Исключительные права на результаты интеллектуальной деятельности (РИД), созданные при оказании услуг, переходят к Заказчику в полном объеме с момента подписания итогового Акта сдачи-приемки и поступления 100% оплаты.' 
  : 'Исполнитель сохраняет за собой авторские и исключительные права на типовые модули и наработки, предоставляя Заказчику простую неисключительную лицензию.'}

4. ПРИЕМКА УСЛУГ И ОТВЕТСТВЕННОСТЬ СТОРОН
4.1. Заказчик обязуется рассмотреть и подписать Акт сдачи-приемки в течение 7 (семи) рабочих дней либо направить мотивированный отказ.
4.2. За нарушение сроков виновная Сторона уплачивает пени в размере ${data.penaltyRate || 0.1}% за каждый день просрочки от стоимости неисполненного обязательства (но суммарно не более 10%).

5. ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ
5.1. Все споры подлежат рассмотрению в ${data.jurisdiction || 'Арбитражном суде города Москвы'}.
5.2. Стороны признают юридическую силу электронных документов, подписанных квалифицированной ЭЦП либо направленных через доверенные адреса корпоративной почты.`;
}

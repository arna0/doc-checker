import { ContractAudit } from '../types';

export function exportProtocolOfDisagreements(audit: ContractAudit): void {
  const currentDate = new Date().toLocaleDateString('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  });

  let protocolText = `CONTRACT REDLINE & NEGOTIATION PROTOCOL
Contract: ${audit.title}
Counterparty: ${audit.counterparty}
Date of Review: ${currentDate}
System: LexGuard AI (Legal Intelligence Engine)

================================================================================
EXECUTIVE SUMMARY
Initial Safety Score: ${audit.score}/100
Total Issues Identified: ${audit.risks.length} clauses
Status: All proposed redlines balance bilateral rights, eliminate unilateral liability,
and establish commercially standard terms.
================================================================================
`;

  audit.risks.forEach((risk, index) => {
    protocolText += `
[ITEM ${index + 1}] Clause ${risk.clauseNumber} — ${risk.clauseTitle}
SEVERITY: ${risk.severity === 'CRITICAL' ? 'CRITICAL RISK' : risk.severity === 'MEDIUM' ? 'WARNING' : 'ADVISORY'}
CATEGORY: ${risk.category}
LEGAL REFERENCE: ${risk.articleRef || 'Statutory Compliance / Uniform Commercial Code'}

1. COUNTERPARTY'S ORIGINAL CLAUSE:
${risk.originalText}

2. LEXGUARD RECOMMENDED CLAUSE (BALANCED REDLINE):
${risk.proposedClause}

3. LEGAL RATIONALE & DOCTRINE:
${risk.description}
Impact: ${risk.consequence}
Recommendation: ${risk.recommendation}

Status in Review: ${risk.status.toUpperCase()}
--------------------------------------------------------------------------------
`;
  });

  protocolText += `
SIGNATURES & ACKNOWLEDGEMENT OF TERMS:

For and on behalf of Client:                    For and on behalf of Contractor / Supplier:
Signature: _______________________              Signature: _______________________
Name: ____________________________              Name: ____________________________
Title: ___________________________              Title: ___________________________
Date: ____________________________              Date: ____________________________

Generated by LexGuard AI Contract Intelligence System.
`;

  const blob = new Blob([protocolText], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `Negotiation_Protocol_${audit.id}.txt`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

